/// Add or edit an asset (managers only). The asset code is generated by
/// the repository when a new asset is saved.
class AssetFormPage extends StatelessWidget {
  const AssetFormPage({super.key, this.assetId});

  final String? assetId;

  @override
  Widget build(BuildContext context) {
    return BlocProvider(
      create: (_) => sl<AssetFormCubit>()..load(assetId: assetId),
      child: const _FormView(),
    );
  }
}

class _FormView extends StatefulWidget {
  const _FormView();

  @override
  State<_FormView> createState() => _FormViewState();
}

class _FormViewState extends State<_FormView> {
  final _key = GlobalKey<FormState>();
  final _name = TextEditingController();
  final _brand = TextEditingController();
  final _model = TextEditingController();
  final _serial = TextEditingController();
  final _assignedTo = TextEditingController();
  final _notes = TextEditingController();
  AssetCategory _category = AssetCategory.laptop;
  AssetStatus _status = AssetStatus.active;
  String? _siteId;
  String? _locationId;
  DateTime? _purchase;
  DateTime? _warranty;
  bool _filled = false;

  @override
  void dispose() {
    for (final c in [_name, _brand, _model, _serial, _assignedTo, _notes]) {
      c.dispose();
    }
    super.dispose();
  }

  void _fill(Asset a) {
    if (_filled) return;
    _filled = true;
    _name.text = a.name;
    _brand.text = a.brand;
    _model.text = a.model;
    _serial.text = a.serial;
    _assignedTo.text = a.assignedTo;
    _notes.text = a.notes;
    _category = a.category;
    _status = a.status;
    _siteId = a.siteId;
    _locationId = a.locationId;
    _purchase = a.purchaseDate;
    _warranty = a.warrantyUntil;
  }

  Future<DateTime?> _pickDate(DateTime? initial) => showDatePicker(
    context: context,
    initialDate: initial ?? DateTime.now(),
    firstDate: DateTime(2000),
    lastDate: DateTime(2100),
  );

  @override
  Widget build(BuildContext context) {
    final l10n = AppLocalizations.of(context);
    final date = DateFormat.yMMMd(Localizations.localeOf(context).toString());

    return BlocConsumer<AssetFormCubit, AssetFormState>(
      listener: (context, state) {
        if (state.status == AssetFormStatus.saved) {
          ScaffoldMessenger.of(context)
            ..hideCurrentSnackBar()
            ..showSnackBar(SnackBar(content: Text(l10n.savedMessage)));
          context.pop();
        } else if (state.error != null) {
          ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text(state.error!)));
        }
      },
      builder: (context, state) {
        final isNew = state.asset.isNew;
        if (state.status != AssetFormStatus.loading) _fill(state.asset);
        final locations = state.locations.where((l) => l.siteId == _siteId).toList();

        return Scaffold(
          appBar: AppBar(title: Text(isNew ? l10n.addAsset : l10n.editAsset)),
          body: state.status == AssetFormStatus.loading
              ? const LoadingView()
              : Form(
                  key: _key,
                  child: ListView(
                    padding: const EdgeInsets.fromLTRB(16, 16, 16, 32),
                    children: [
                      Legend(l10n.assetCodeLabel),
                      const SizedBox(height: 4),
                      Text(
                        isNew ? l10n.codeOnSave : state.asset.code,
                        style: isNew
                            ? Theme.of(context).textTheme.bodyMedium
                            : AppTheme.mono(context, size: 16),
                      ),
                      const SizedBox(height: 20),
                      TextFormField(
                        controller: _name,
                        decoration: InputDecoration(labelText: l10n.fieldName),
                        validator: (v) => (v ?? '').trim().isEmpty ? l10n.requiredField : null,
                      ),
                      const SizedBox(height: 12),
                      DropdownButtonFormField<AssetCategory>(
                        initialValue: _category,
                        decoration: InputDecoration(labelText: l10n.fieldCategory),
                        items: [
                          for (final c in AssetCategory.values)
                            DropdownMenuItem(value: c, child: Text(c.label(l10n))),
                        ],
                        onChanged: isNew ? (v) => setState(() => _category = v!) : null,
                      ),
                      const SizedBox(height: 12),
                      Row(
                        children: [
                          Expanded(
                            child: TextFormField(
                              controller: _brand,
                              decoration: InputDecoration(labelText: l10n.fieldBrand),
                            ),
                          ),
                          const SizedBox(width: 12),
                          Expanded(
                            child: TextFormField(
                              controller: _model,
                              decoration: InputDecoration(labelText: l10n.fieldModel),
                            ),
                          ),
                        ],
                      ),
                      const SizedBox(height: 12),
                      TextFormField(
                        controller: _serial,
                        decoration: InputDecoration(labelText: l10n.fieldSerial),
                      ),
                      const SizedBox(height: 12),
                      DropdownButtonFormField<AssetStatus>(
                        initialValue: _status,
                        decoration: InputDecoration(labelText: l10n.fieldStatus),
                        items: [
                          for (final s in AssetStatus.values)
                            DropdownMenuItem(value: s, child: Text(s.label(l10n))),
                        ],
                        onChanged: (v) => setState(() => _status = v!),
                      ),
                      const SizedBox(height: 12),
                      DropdownButtonFormField<String>(
                        initialValue: state.sites.any((s) => s.id == _siteId) ? _siteId : null,
                        decoration: InputDecoration(labelText: l10n.fieldSite),
                        items: [
                          for (final s in state.sites)
                            DropdownMenuItem(value: s.id, child: Text(s.name)),
                        ],
                        onChanged: (v) => setState(() {
                          _siteId = v;
                          _locationId = null;
                        }),
                      ),
                      const SizedBox(height: 12),
                      DropdownButtonFormField<String>(
                        key: ValueKey(_siteId),
                        initialValue: locations.any((l) => l.id == _locationId) ? _locationId : null,
                        decoration: InputDecoration(labelText: l10n.fieldLocation),
                        items: [
                          for (final l in locations)
                            DropdownMenuItem(value: l.id, child: Text(l.name)),
                        ],
                        onChanged: (v) => setState(() => _locationId = v),
                      ),
                      const SizedBox(height: 12),
                      TextFormField(
                        controller: _assignedTo,
                        decoration: InputDecoration(labelText: l10n.fieldAssignedTo),
                      ),
                      const SizedBox(height: 12),
                      Row(
                        children: [
                          Expanded(
                            child: _DateField(
                              label: l10n.fieldPurchase,
                              value: _purchase == null ? '' : date.format(_purchase!),
                              onTap: () async {
                                final d = await _pickDate(_purchase);
                                if (d != null) setState(() => _purchase = d);
                              },
                            ),
                          ),
                          const SizedBox(width: 12),
                          Expanded(
                            child: _DateField(
                              label: l10n.fieldWarranty,
                              value: _warranty == null ? '' : date.format(_warranty!),
                              onTap: () async {
                                final d = await _pickDate(_warranty);
                                if (d != null) setState(() => _warranty = d);
                              },
                            ),
                          ),
                        ],
                      ),
                      const SizedBox(height: 12),
                      TextFormField(
                        controller: _notes,
                        minLines: 2,
                        maxLines: 4,
                        decoration: InputDecoration(labelText: l10n.fieldNotes),
                      ),
                      const SizedBox(height: 24),
                      PrimaryButton(
                        label: l10n.saveAction,
                        isLoading: state.status == AssetFormStatus.saving,
                        onPressed: () {
                          if (!(_key.currentState?.validate() ?? false)) return;
                          context.read<AssetFormCubit>().save(
                            state.asset.copyWith(
                              name: _name.text.trim(),
                              category: _category,
                              status: _status,
                              brand: _brand.text.trim(),
                              model: _model.text.trim(),
                              serial: _serial.text.trim(),
                              siteId: _siteId,
                              locationId: _locationId,
                              assignedTo: _assignedTo.text.trim(),
                              purchaseDate: _purchase,
                              warrantyUntil: _warranty,
                              notes: _notes.text.trim(),
                            ),
                          );
                        },
                      ),
                    ],
                  ),
                ),
        );
      },
    );
  }
}

class _DateField extends StatelessWidget {
  const _DateField({required this.label, required this.value, required this.onTap});

  final String label;
  final String value;
  final VoidCallback onTap;

  @override
  Widget build(BuildContext context) {
    return InkWell(
      onTap: onTap,
      borderRadius: BorderRadius.circular(12),
      child: InputDecorator(
        decoration: InputDecoration(
          labelText: label,
          suffixIcon: const Icon(Icons.calendar_today_outlined, size: 18),
        ),
        child: Text(value.isEmpty ? ' ' : value, maxLines: 1, overflow: TextOverflow.ellipsis),
      ),
    );
  }
}
